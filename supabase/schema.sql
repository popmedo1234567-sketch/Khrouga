create table if not exists public.places (
  id          integer generated by default as identity primary key,
  slug        text        not null unique,
  name        text        not null,
  area        text        not null,
  address     text        not null,
  type        text        not null,
  moods       text[]      not null default '{}',
  tags        text[]      not null default '{}',
  avg_price   integer     not null default 0,
  menu_items  jsonb       not null default '[]'::jsonb,
  image_url   text,
  gallery     jsonb       not null default '[]'::jsonb,
  reel_url    text,
  whatsapp    text,
  maps_url    text,
  rating      real        not null default 0,
  hours       text,
  notes       text,
  featured    boolean     not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists places_area_idx  on public.places (area);
create index if not exists places_type_idx  on public.places (type);
create index if not exists places_price_idx on public.places (avg_price);
create index if not exists places_moods_idx on public.places using gin (moods);

comment on column public.places.avg_price  is 'متوسط سعر الفرد بالجنيه المصري';
comment on column public.places.menu_items is '[{ "name": "...", "price": 0, "note": "..." }]';
comment on column public.places.updated_at is 'آخر مراجعة للأسعار — بتظهر للمستخدم كعلامة ثقة';

-- Row Level Security: القراءة عامة، والكتابة للسيرفر فقط (service_role / admin API)
alter table public.places enable row level security;

drop policy if exists "places_public_read" on public.places;
create policy "places_public_read" on public.places for select using (true);

-- (اختياري) تحديث updated_at تلقائيًا من الداتابيز
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists places_touch_updated_at on public.places;
create trigger places_touch_updated_at
  before update on public.places
  for each row execute function public.touch_updated_at();

